import { useSyncExternalStore } from "react";

export type DashboardLanguage = "en" | "de";
const storageKey = "glanzio-dashboard-language";
const changeEvent = "glanzio-dashboard-language-change";
let fallbackLanguage: DashboardLanguage = "en";

function subscribe(callback: () => void) {
  window.addEventListener("storage", callback);
  window.addEventListener(changeEvent, callback);
  return () => {
    window.removeEventListener("storage", callback);
    window.removeEventListener(changeEvent, callback);
  };
}

function readLanguage(): DashboardLanguage {
  try {
    const saved = window.localStorage.getItem(storageKey);
    return saved === "de" || saved === "en" ? saved : fallbackLanguage;
  } catch {
    return fallbackLanguage;
  }
}

