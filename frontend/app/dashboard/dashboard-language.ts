export function useDashboardLanguage() {
  const language = useSyncExternalStore(subscribe, readLanguage, () => "en" as const);
  function setLanguage(next: DashboardLanguage) {
    fallbackLanguage = next;
    try {
      window.localStorage.setItem(storageKey, next);
    } catch { /* Keep the selection for this tab when storage is unavailable. */ }
    window.dispatchEvent(new Event(changeEvent));
  }
  function t(text: string): string {
    if (language === "en") return text;
    const trimmed = text.trim();
    const translated = germanDashboardCopy[trimmed];
    return translated ? text.replace(trimmed, translated) : text;
  }
  return { language, setLanguage, t, locale: language === "de" ? "de-DE" : "en-GB" };
}
